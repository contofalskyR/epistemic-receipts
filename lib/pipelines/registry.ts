export type PipelineStatus = 'in-production' | 'dry-run-pending';
export type SourceCategory =
  | "US Federal Government"
  | "Courts & Legal"
  | "Science & Medicine"
  | "International Organizations"
  | "Pharmaceutical & Health"
  | "National Parliaments / Legislation"
  | "Archives & Historical"
  | "Editorial / Curated"
  | "Other";

