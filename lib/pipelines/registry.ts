// ─── The pipeline registry ───────────────────────────────────────────────────
// ONE registry (front door phase 3, 2026-09-30). It used to be three that
// disagreed: this file (data cards, 103 tags), SOURCE_REGISTRY in
// app/api/sources-summary (185 tags with categories) and PIPELINE_REGISTRY in
// app/pipelines (78 tags with status). /datasets, /sources and /pipelines all
// derive from PIPELINES now. Entries with a `method` are data pipelines with a
// provenance card; the rest are editorial/seed tags that only need a label.

