export function getPipeline(tag: string): PipelineEntry | undefined {
  return PIPELINES.find(p => p.tag === tag);
}

/** Data pipelines (have a fetch method) that are not retired — the /datasets cards. */
export function getActivePipelines(): PipelineEntry[] {
  return PIPELINES.filter(p => !p.retired && !!p.method);
}

/** Every pipeline with a provenance card, retired ones included. */
export function getDataPipelines(): PipelineEntry[] {
  return PIPELINES.filter(p => !!p.method);
}
