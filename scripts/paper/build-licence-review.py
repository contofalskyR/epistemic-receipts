#!/usr/bin/env python3
"""build-licence-review.py — docs/paper/licence-review.md from docs/paper/upstream-licences.csv.

    python3 scripts/paper/build-licence-review.py

Lists every pipeline whose upstream status is not `open`, the owner's decision (exclude /
include with per-row licence), and the unresolved pipelines above 10,000 claims.
"""
import csv
from collections import defaultdict

rows = list(csv.DictReader(open("docs/paper/upstream-licences.csv")))
n = lambda r: int(r["claims"])
agg = defaultdict(lambda: [0, 0])
for r in rows:
    agg[r["status"]][0] += 1
    agg[r["status"]][1] += n(r)
excl = [r for r in rows if r["decision"] == "exclude"]
out = [
    "# Upstream licence review",
    "",
    "Generated by `scripts/paper/build-licence-review.py` from `docs/paper/upstream-licences.csv` (one row per pipeline, "
    "with the page each statement came from; checked 2026-10-24). Dataset licence: CC BY 4.0. *Scientific Data* allows "
    "-NC / -SA only when inherited from third-party primary data, and nothing compiled from -ND inputs "
    "(`journal-requirements.md`).",
    "",
    "**Owner decisions (2026-10-24):** exclude every `restricted` pipeline (UN included), SIPRI, and `cyprus_legislation_v1` (a third-party note of a redistribution ban, until a primary source says otherwise); keep `nc` and `sa` "
    "pipelines with the per-row licence columns (`claims.upstreamLicence`, `claims.upstreamLicenceStatus`); keep "
    "`unclear` and `not_checked` with a per-row status for this export. `scripts/paper/export.ts` reads the `decision` "
    "column: excluded pipelines lose their claims and everything attached, and are listed in `MANIFEST.excludedPipelines`.",
    "",
    "Not legal advice: the export ships our own claim text plus upstream identifiers, dates, metadata fields and links. "
    "This list records only what each provider (or statute) says.",
    "",
    "## Totals",
    "",
    "| Status | Pipelines | Claims |",
    "|---|---:|---:|",
]
for st in ["open", "sa", "nc", "restricted", "unclear", "not_checked"]:
    out.append(f"| {st} | {agg[st][0]} | {agg[st][1]:,} |")
out += [
    f"| **total** | {len(rows)} | {sum(map(n, rows)):,} |",
    "",
    f"**Excluded from the export: {len(excl)} pipelines, {sum(map(n, excl)):,} claims.**",
    "",
    "## Excluded",
    "",
    "| Pipeline | Claims | Status | What the terms say | Source |",
    "|---|---:|---|---|---|",
]
for r in sorted(excl, key=lambda r: -n(r)):
    out.append(f"| `{r['pipeline']}` | {n(r):,} | {r['status']} | {r['licence']} | [link]({r['licence_url']}) |")
for st, title in [("nc", "Kept with per-row licence: nc"), ("sa", "Kept with per-row licence: sa"), ("unclear", "Kept with per-row status: unclear")]:
    rs = sorted([r for r in rows if r["status"] == st and r["decision"] != "exclude"], key=lambda r: -n(r))
    out += ["", f"## {title} ({len(rs)} pipelines, {sum(map(n, rs)):,} claims)", "", "| Pipeline | Claims | What the terms say | Source |", "|---|---:|---|---|"]
    for r in rs:
        note = f" ({r['note']})" if r["note"] else ""
        src = f"[link]({r['licence_url']})" if r["licence_url"] else "—"
        out.append(f"| `{r['pipeline']}` | {n(r):,} | {r['licence']}{note} | {src} |")
rs = sorted([r for r in rows if r["status"] == "not_checked"], key=lambda r: -n(r))
out += ["", f"## Kept with per-row status: not_checked ({len(rs)} pipelines, {sum(map(n, rs)):,} claims)", "", "| Pipeline | Claims | Upstream |", "|---|---:|---|"]
out += [f"| `{r['pipeline']}` | {n(r):,} | {r['upstream']} |" for r in rs]
big = sorted([r for r in rows if r["status"] in ("unclear", "not_checked") and r["decision"] != "exclude" and n(r) > 10000], key=lambda r: -n(r))
out += ["", f"## Still unresolved above 10,000 claims ({len(big)})", ""]
out += [f"- `{r['pipeline']}` ({n(r):,}): {r['licence']}" for r in big]
out.append("")
open("docs/paper/licence-review.md", "w").write("\n".join(out))
print(f"wrote docs/paper/licence-review.md; excluded {len(excl)} / {sum(map(n, excl)):,}; unresolved >10k {len(big)}")
